/**
 * Get advanced moves for a specific class and level range
 */
export function getAdvancedMovesForClass(
  characterClass: CharacterClass,
  minLevel: number,
  maxLevel: number,
): AdvancedMove[] {
  return ADVANCED_MOVES.filter(move =>
    move.class === characterClass &&
    move.level >= minLevel &&
    move.level <= maxLevel,
  );
}

/**
 * Get all advanced moves for a class at a specific level
 */
export function getAdvancedMovesAtLevel(
  characterClass: CharacterClass,
  level: number,
): AdvancedMove[] {
  return ADVANCED_MOVES.filter(move =>
    move.class === characterClass &&
    move.level === level,
  );
}

